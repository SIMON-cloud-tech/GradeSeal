import { useState, useEffect } from 'react';
import { FiSearch, FiDownload, FiCheckCircle, FiClock } from 'react-icons/fi';
import '../css/CoasManage.css';

//Define the api base to use when fetching the coas from the server.
//This is a relative path to the server's API endpoint.
const API_URL = '/api/coas';

const COAsManage = () => {
  const [coas, setCoas] = useState([]);
  const [loading, setLoading] = useState(true);
  const [search, setSearch] = useState('');

  // Fetch from backend
  useEffect(() => {
    const fetchCOAs = async () => {
      setLoading(true);
      try {
        const res = await fetch(`${API_URL}?search=${search}`, { credentials: 'include' });
        if (!res.ok) throw new Error('Failed to fetch COAs');
        const data = await res.json();
        setCoas(data);
      } catch (err) {
        console.error("Failed to load COAs:", err);
        // Fallback to empty array so UI doesn't break
        setCoas([]);
      } finally {
        setLoading(false);
      }
    };

    // Debounce the search slightly
    const timer = setTimeout(() => {
      fetchCOAs();
    }, 300);

    return () => clearTimeout(timer);
  }, [search]);

  const getStatusBadge = (status) => {
    if (status === 'Approved') return <span className="coa-badge coa-signed"><FiCheckCircle /> Signed</span>;
    if (status === 'Pending Approval') return <span className="coa-badge coa-pending"><FiClock /> Pending</span>;
    return <span className="coa-badge coa-sent">Printed</span>;
  };

  return (
    <div className="coa-container">
      <div className="coa-header">
        <h2>Certificates of Analysis</h2>
        <p>Master repository of all COAs generated by the system.</p>
      </div>

      <div className="coa-search-wrapper">
        <FiSearch className="coa-search-icon" />
        <input
          type="text"
          className="coa-search-input"
          placeholder="Search by COA, Batch, or Client..."
          value={search}
          onChange={(e) => setSearch(e.target.value)}
        />
      </div>

      <div className="coa-table-wrapper">
        <table className="coa-table">
          <thead>
            <tr>
              <th>COA Number</th>
              <th>Batch</th>
              <th>Client</th>
              <th>Date Issued</th>
              <th>Status</th>
              <th>Bag QRs</th>
              <th>Action</th>
            </tr>
          </thead>
          <tbody>
            {loading && coas.length === 0 ? (
              <tr><td colSpan={7} style={{ textAlign: 'center', padding: '2rem' }}>Loading...</td></tr>
            ) : coas.length > 0 ? (
              coas.map(coa => (
                <tr key={coa._id}>
                  <td><strong>{coa.coaId}</strong></td>
                  <td>{coa.batch?.batchNo || 'N/A'}</td>
                  <td>{coa.batch?.client || 'N/A'}</td>
                  <td>{new Date(coa.createdAt).toLocaleDateString()}</td>
                  <td>{getStatusBadge(coa.status)}</td>
                  <td>{coa.qrCount} QRs</td>
                  <td>
                    <a 
                      href={coa.coaPdfUrl || '#'} 
                      target="_blank" 
                      rel="noreferrer"
                      className="coa-download-btn"
                      style={{ textDecoration: 'none', display: 'inline-flex', alignItems: 'center', gap: '0.3rem' }}
                    >
                      <FiDownload /> PDF
                    </a>
                  </td>
                </tr>
              ))
            ) : (
              <tr><td colSpan={7} style={{ textAlign: 'center', padding: '2rem' }}>No COAs found.</td></tr>
            )}
          </tbody>
        </table>
      </div>
    </div>
  );
};

export default COAsManage;